  assert.equal(isolated, 'allow-scripts');
  const child = page.frames().find(item => item.parentFrame());
  assert.deepEqual(await child.evaluate(() => {
    let dom = false, storage = false;
    try { void parent.document.body; } catch { dom = true; }
    try { void localStorage.length; } catch { storage = true; }
    return { dom, storage };
  }), { dom: true, storage: true });
