  let release, received;
  const gate = new Promise(resolve => { release = resolve; }), request = new Promise(resolve => { received = resolve; });
  await page.route('**/api/plugins', async route => { received(); await gate; await route.continue(); });
  const switched = child.evaluate(async () => { try { await moa.context(); return ''; } catch (error) { return error.message; } });
  await request;
  await page.evaluate(() => localStorage.setItem('moa.profile', 'changed-profile'));
  release(); assert.match(await switched, /프로필이 변경/);
  await page.evaluate(id => localStorage.setItem('moa.profile', id), profile.id);
  await page.unroute('**/api/plugins');
  await env.app.inject({ method: 'POST', url: '/api/admin/plugins', payload: { ...manifest, version: '1.0.1', html } });
  assert.match(await child.evaluate(async () => { try { await moa.context(); return ''; } catch (error) { return error.message; } }), /업데이트/);
  await page.getByRole('button', { name: '플러그인 닫기' }).click();
  await page.getByLabel('플러그인 파일', { exact: true }).setInputFiles({ name: 'update.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...manifest, version: '1.0.2', html })) });
  await page.getByRole('button', { name: '설치·업데이트', exact: true }).click();
  await row.getByText('1.0.2', { exact: true }).waitFor();
  await row.getByRole('button', { name: '열기', exact: true }).click();
  await page.frameLocator('.plugin-dialog iframe').getByText('재생 화면의 자막 및 음성 메뉴에서 이 도구를 열어 주세요.', { exact: true }).waitFor();
  await page.getByRole('button', { name: '플러그인 닫기' }).click();
  await row.getByRole('switch').click();
  await page.waitForFunction(() => document.querySelector('.plugin-row [role=switch]').getAttribute('aria-checked') === 'false');
  assert.equal(await row.getByRole('button', { name: '열기', exact: true }).count(), 0);
  await page.reload();
  assert.equal(await row.getByRole('switch').getAttribute('aria-checked'), 'false');
  await row.getByRole('switch').click();
  await page.waitForFunction(() => document.querySelector('.plugin-row [role=switch]').getAttribute('aria-checked') === 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  await row.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: verificationPath('plugins-390.png'), animations: 'disabled' });
  await page.route('**/fixture/plugin.mp4', route => route.fulfill({ contentType: 'video/mp4', body: video }));
  await page.route('**/api/playback', route => route.fulfill({ json: { sessionId: 'plugin', episodeId: 'e1', mediaId: 'm', mediaTitle: 'Plugin fixture', mediaType: 'movie', mode: 'direct', mime: 'video/mp4', url: '/fixture/plugin.mp4', duration: 600, startPosition: 0, subtitles: [], audioTracks: [] } }));
  await page.goto(base + 'tests/fixtures/player.html');
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
  await page.locator('video').evaluate(element => element.pause());
  await page.getByRole('button', { name: '자막 및 음성', exact: true }).click();
  await page.getByRole('button', { name: '자막 가져오기 도구 플러그인', exact: true }).click();
  frame = page.frameLocator('.plugin-dialog iframe');
  await frame.getByText('Plugin fixture', { exact: true }).waitFor();
  await frame.getByLabel('자막 내용', { exact: true }).fill('WEBVTT\n\n00:00:00.000 --> 00:10:00.000\nPlugin subtitle\n');
  await frame.getByRole('button', { name: '내용을 자막으로 저장', exact: true }).click();
  await frame.getByText('서버에 저장했어요. 창을 닫고 자막을 확인해 주세요.', { exact: true }).waitFor();
  await page.getByRole('button', { name: '플러그인 닫기', exact: true }).click();
  await page.getByRole('button', { name: 'pasted.vtt', exact: true }).waitFor();
